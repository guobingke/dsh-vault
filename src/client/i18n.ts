export const dictionaries: Record<Locale, Record<MessageKey, string>> = { zh, en }

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  const dict = dictionaries[locale] ?? zh
  let text: string = dict[key] ?? dictionaries.zh[key] ?? key
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value))
    }
  }
  return text
}

/** Normalize a host locale tag ("zh-CN", "en-US", "ja") to a UI locale. */
export function normalizeLocale(tag: string | undefined | null): Locale {
  if (tag && /^en/i.test(tag)) return 'en'
  return 'zh'
}

export function detectInitialLocale(hostTag?: string | null): Locale {
  const stored = readStoredLocale()
  if (stored) return stored
  if (hostTag) return normalizeLocale(hostTag)
  if (typeof navigator !== 'undefined' && navigator.language) return normalizeLocale(navigator.language)
  return 'zh'
}

export function readStoredLocale(): Locale | null {
  try {
    if (typeof localStorage === 'undefined') return null
    const v = localStorage.getItem(LOCALE_STORAGE_KEY)
    return v === 'zh' || v === 'en' ? v : null
  } catch {
    return null
  }
}

export function storeLocale(locale: Locale): void {
  try {
    if (typeof localStorage !== 'undefined') localStorage.setItem(LOCALE_STORAGE_KEY, locale)
  } catch {
    // storage may be unavailable (private mode) — non-fatal
  }
}

export interface I18nValue {
  locale: Locale
  t: Translate
}

const zhTranslate: Translate = (key, vars) => translate('zh', key, vars)

/** Context carrying the active locale + translator. Components call `useT()` / `useLocale()`. */
export const I18nContext = createContext<I18nValue>({ locale: 'zh', t: zhTranslate })

export function useI18n(): I18nValue {
  return useContext(I18nContext)
}

export function useT(): Translate {
  return useContext(I18nContext).t
}

export function useLocale(): Locale {
  return useContext(I18nContext).locale
}
